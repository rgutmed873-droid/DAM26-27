def media(lista):
    """Calcula y devuelve la media de una lista de números."""
    #Sumo todos los números de la lista y luego la divido por la cantidad de números
    return sum(lista) / len(lista)
    

def mayor(lista):
    """Devuelve el número más alto de la lista."""
    return max(lista)
    

def menor(lista):
    """Devuelve el número más bajo de la lista."""
    return min(lista)
    